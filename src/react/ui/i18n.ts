const tables: Readonly<Record<SoothLocale, SoothStringTable>> = { en, zh };

export type SoothTextVars = Readonly<Record<string, string | number>>;

/** Replace `{name}` placeholders; unknown placeholders are left visible. */
export function interpolate(template: string, vars?: SoothTextVars): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match,
  );
}

export interface SoothStrings {
  readonly locale: SoothLocale;
  readonly table: SoothStringTable;
  t(key: SoothStringKey, vars?: SoothTextVars): string;
}

/** String lookup for a widget locale; unknown locales fall back to English. */
export function soothText(locale: SoothLocale = 'en'): SoothStrings {
  const resolved: SoothLocale = locale === 'zh' ? 'zh' : 'en';
  const table = tables[resolved];
  return {
    locale: resolved,
    table,
    t: (key, vars) => interpolate(table[key], vars),
  };
}
